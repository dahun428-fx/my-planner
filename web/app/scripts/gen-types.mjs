#!/usr/bin/env node
// BE schema bundle -> src/api/schema.json -> src/api/types.gen.ts
// (same rules as the dashboard's gen-types, SP3-4 plan 16).
// MP_SCHEMA_CMD overrides the command; default `python -m my_planner schema`, run at the repo root.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = join(here, "..");
const repoRoot = join(appRoot, "..", "..");
const cmd = process.env.MP_SCHEMA_CMD || "python -m my_planner schema";

const raw = execSync(cmd, { cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
const bundle = JSON.parse(raw);
if (bundle.api !== "v1" || typeof bundle.models !== "object" || bundle.models === null) {
  throw new Error("schema output is not {api: \"v1\", models: {...}}");
}

const sortKeys = (v) =>
  Array.isArray(v)
    ? v.map(sortKeys)
    : v && typeof v === "object"
      ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])]))
      : v;

const ordered = sortKeys(bundle);
writeFileSync(join(appRoot, "src/api/schema.json"), JSON.stringify(ordered, null, 2) + "\n");

// Property titles ("Checked At") would become named aliases (`type Date = string`); drop them
// so only models and $defs are named types.
const dropTitles = (v) =>
  Array.isArray(v)
    ? v.map(dropTitles)
    : v && typeof v === "object"
      ? Object.fromEntries(
          Object.entries(v)
            .filter(([k, x]) => !(k === "title" && typeof x === "string"))
            .map(([k, x]) => [k, k === "properties" ? propMap(x) : dropTitles(x)]),
        )
      : v;
const propMap = (props) => Object.fromEntries(Object.entries(props).map(([k, x]) => [k, dropTitles(x)]));
const named = (name, schema) => ({ ...dropTitles(schema), title: name });

// Hoist every model and its $defs into one document so shared definitions are emitted once.
const defs = {};
const put = (name, schema) => {
  if (name in defs && JSON.stringify(defs[name]) !== JSON.stringify(schema)) {
    throw new Error(`conflicting definitions for ${name}`);
  }
  defs[name] = schema;
};
const names = Object.keys(ordered.models);
for (const name of names) {
  const { $defs = {}, ...model } = ordered.models[name];
  for (const [n, s] of Object.entries($defs)) {
    if (!names.includes(n)) put(n, named(n, s));
  }
  put(name, named(name, model));
}
for (const name of names) {
  const { $defs = {} } = ordered.models[name];
  for (const [n, s] of Object.entries($defs)) {
    if (names.includes(n)) {
      if (JSON.stringify(defs[n]) !== JSON.stringify(named(n, s))) throw new Error(`model ${n} differs from its $def`);
    }
  }
}

const root = {
  title: "ApiModels",
  type: "object",
  additionalProperties: false,
  required: names,
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
  $defs: defs,
};

const ts = await compile(root, "ApiModels", {
  bannerComment:
    "/* Generated by scripts/gen-types.mjs from src/api/schema.json. Do not edit; run `npm run gen:types`. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  format: true,
  style: { semi: true, singleQuote: false, printWidth: 100 },
});
writeFileSync(join(appRoot, "src/api/types.gen.ts"), ts);
console.log(`types: ${names.length} models -> src/api/types.gen.ts`);
