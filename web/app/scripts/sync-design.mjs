#!/usr/bin/env node
// DESIGN.md: web/shared/global.css is the design system's single source. Vercel builds this app
// with root web/app and its ignoreCommand diffs only web/app, so the app keeps its own copy at
// src/styles/global.css (imported by _app). This writes that copy under a generated-file header;
// sync-design.test.mjs fails when the copy and the source differ.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE = fileURLToPath(new URL("../../shared/global.css", import.meta.url));
export const TARGET = fileURLToPath(new URL("../src/styles/global.css", import.meta.url));
export const HEADER =
  "/* GENERATED by `npm run sync:design` from web/shared/global.css. Do not edit this copy:\n" +
  "   change the source (and DESIGN.md) and run the script again. */";

export function designCopy(source) {
  return `${HEADER}\n${source}`;
}

/** Write the copy; true when it changed. */
export function syncDesign(source = SOURCE, target = TARGET) {
  const next = designCopy(readFileSync(source, "utf8"));
  if (existsSync(target) && readFileSync(target, "utf8") === next) return false;
  writeFileSync(target, next);
  return true;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const changed = syncDesign();
  console.log(changed ? "sync:design: wrote src/styles/global.css" : "sync:design: src/styles/global.css is up to date");
}
