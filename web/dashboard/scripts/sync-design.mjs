#!/usr/bin/env node
// DESIGN.md: web/shared/global.css is the design system's single source. Vercel builds the dashboard
// with root web/dashboard and its ignoreCommand diffs only web/dashboard, so it keeps its own copy at
// src/styles/global.css (imported by _app). This writes that copy under a generated-file header;
// sync-design.test.mjs fails when the copy and the source differ. It also turns web/shared/pictograms.svg
// into src/components/pictograms.gen.tsx.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE = fileURLToPath(new URL("../../shared/global.css", import.meta.url));
export const TARGET = fileURLToPath(new URL("../src/styles/global.css", import.meta.url));
export const HEADER =
  "/* GENERATED by `npm run sync:design` from web/shared/global.css. Do not edit this copy:\n" +
  "   change the source (and DESIGN.md) and run the script again. */";

export function designCopy(source) {
  return `${HEADER}\n${source}`;
}

export const PICTO_SOURCE = fileURLToPath(new URL("../../shared/pictograms.svg", import.meta.url));
export const PICTO_TARGET = fileURLToPath(new URL("../src/components/pictograms.gen.tsx", import.meta.url));
export const PICTO_HEADER = "// GENERATED by `npm run sync:design` from web/shared/pictograms.svg";

/** The <symbol>s of the sprite: id without the "p-" prefix and the markup between the tags. */
export function parseSymbols(svg) {
  return [...svg.matchAll(/<symbol id="p-([a-z_]+)" viewBox="0 0 24 24">([\s\S]*?)<\/symbol>/g)].map((m) => ({
    id: m[1],
    children: m[2].trim(),
  }));
}

const jsxAttr = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const jsxChildren = (markup) => markup.replace(/(\s)([a-z]+(?:-[a-z]+)+)=/g, (_, sp, name) => `${sp}${jsxAttr(name)}=`);

/** The generated React module: names, the sprite and the component. */
export function pictogramsModule(svg) {
  const symbols = parseSymbols(svg);
  const names = symbols.map((s) => `  "${s.id}",`).join("\n");
  const jsx = symbols
    .map((s) => `      <symbol id="p-${s.id}" viewBox="0 0 24 24">\n        ${jsxChildren(s.children)}\n      </symbol>`)
    .join("\n");
  return `${PICTO_HEADER}
// Do not edit this file: change the source (and DESIGN.md) and run the script again.

export const PICTOGRAM_NAMES = [
${names}
] as const;

export type PictogramName = (typeof PICTOGRAM_NAMES)[number];

/** Drawn once per document, first in <body> (pages/_document). Hidden by .pictogram-sprite in global.css. */
export function PictogramSprite() {
  return (
    <svg className="pictogram-sprite" aria-hidden="true" xmlns="http://www.w3.org/2000/svg">
${jsx}
    </svg>
  );
}

/** A 24px-grid line drawing in currentColor; always beside its name in words, or with a label. */
export function Pictogram({ name, size = 24, label }: { name: PictogramName; size?: 16 | 20 | 24; label?: string }) {
  return (
    <svg
      className={\`pictogram pictogram-\${size}\`}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={size === 16 ? 2 : 1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...(label ? { role: "img", "aria-label": label } : { "aria-hidden": true })}
    >
      <use href={\`#p-\${name}\`} />
    </svg>
  );
}
`;
}

/** Write the CSS copy and the pictogram module; true when either changed. */
export function syncDesign(source = SOURCE, target = TARGET, pictoSource = PICTO_SOURCE, pictoTarget = PICTO_TARGET) {
  let changed = false;
  for (const [path, next] of [
    [target, designCopy(readFileSync(source, "utf8"))],
    [pictoTarget, pictogramsModule(readFileSync(pictoSource, "utf8"))],
  ]) {
    if (existsSync(path) && readFileSync(path, "utf8") === next) continue;
    writeFileSync(path, next);
    changed = true;
  }
  return changed;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const changed = syncDesign();
  console.log(changed ? "sync:design: wrote the CSS copy and pictograms.gen.tsx" : "sync:design: up to date");
}
